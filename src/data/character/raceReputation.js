// src/data/character/raceReputation.js

// Базовые модификаторы репутации при создании персонажа определённой расы.
// Положительные числа = доверие, отрицательные = предубеждение/враждебность.
export const RACE_FACTION_BIAS = {
  human: { 
    union: 15,    // Люди — основа Союза
    traders: 10,  // Нормальные торговые партнёры
    pirates: -20  // Пираты не любят "официалов"
  },
  synth: { 
    union: 5,     // Союз терпит синтов, но не доверяет полностью
    traders: 0,   // Нейтрально
    pirates: -10  // Пираты могут попытаться взломать или продать
  },
  aeon: { 
    union: 25,    // Эоны уважаемы Союзом за мудрость/древность
    traders: 15,  // Торговцы ценят их артефакты
    pirates: -30  // Пираты видят в них лёгкую и богатую добычу
  },
  drakar: { 
    union: -30,   // Драккары — традиционные враги или варвары для Союза
    traders: -20, // Торговцы боятся их агрессии
    pirates: 20   // Пираты уважают силу Драккаров
  },
  mycel: { 
    union: -10,   // Союз не понимает коллективный разум
    traders: 20,  // Торговцы заинтересованы в уникальных ресурсах мицела
    pirates: -15  // Пиратам сложно грабить рой
  },
  voidborn: { 
    union: -40,   // Рождённые в Пустоте вызывают суеверный страх и отвращение
    traders: -30, // Торговцы избегают их
    pirates: 15   // Пираты видят в них потенциальных, хоть и странных, союзников
  },
};

export function getStartingReputation(raceId) {
  const bias = RACE_FACTION_BIAS[raceId] || RACE_FACTION_BIAS.human;
  
  // Возвращаем готовый объект для инициализации state.reputation
  return {
    union: bias.union ?? 0,
    traders: bias.traders ?? 0,
    pirates: bias.pirates ?? 0,
  };
}